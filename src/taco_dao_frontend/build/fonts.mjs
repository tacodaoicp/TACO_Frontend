// Font build steps.
//
// faSubset(): Vite plugin. When a build or the dev server starts it cuts the Font Awesome Pro light,
// regular and solid fonts down to the icons used in src and writes them, with their @font-face rules,
// to src/assets/fonts/fa-subset (generated, never committed: FA Pro font files must not go into a public
// repo). taco.scss loads those rules. They only add faces, the package faces stay declared, so a glyph
// outside a subset's unicode-range still comes from the full font and looks the same.
//
// node build/fonts.mjs <font.ttf>...  writes a lossless WOFF2 next to each TTF (tables kept byte for byte,
// only brotli compressed); used for the text fonts in src/assets/fonts.
import fs from 'node:fs'
import path from 'node:path'
import zlib from 'node:zlib'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'

const APP = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const SRC = path.join(APP, 'src')
const OUT = path.join(SRC, 'assets/fonts/fa-subset')
const FA = path.dirname(createRequire(import.meta.url).resolve('@fortawesome/fontawesome-pro/package.json'))
const STYLES = [['light', 300], ['regular', 400], ['solid', 900]]
// fa- class names put together at runtime: the scan cannot see them, so they would miss the subset
const DYNAMIC = /(?<![\w-])fa-(?:[a-z0-9]+-)*(?:['"`]\s*\+|\$\{|#\{)|['"`]fa-(?:[a-z0-9]+-)*['"`]/g

export default function faSubset() {
  let command
  return {
    name: 'taco-fa-subset',
    configResolved(config) { command = config.command },
    buildStart() {
      const fail = (msg) => (command === 'build' ? this.error(msg) : this.warn(msg))
      const { classes, dynamic } = scanSources()
      if (dynamic.length) fail(`write Font Awesome class names out in full so the font subset includes them:\n  ${dynamic.join('\n  ')}`)
      const wanted = new Map()
      for (const [name, cps] of iconCodepoints()) if (classes.has(name)) for (const cp of cps) wanted.set(cp, name)
      fs.mkdirSync(OUT, { recursive: true })
      let css = '// Generated by build/fonts.mjs on every build and dev server start. Do not edit.\n'
      for (const [style, weight] of STYLES) {
        const file = `fa-${style}-${weight}-subset.woff2`
        const font = (ext) => fs.readFileSync(path.join(FA, 'webfonts', `fa-${style}-${weight}.${ext}`))
        const { ttf, cps } = subset(font('ttf'), font('woff2'), wanted)
        const missing = [...wanted].filter(([cp]) => !cps.includes(cp))
        if (missing.length) fail(`fa-${style}-${weight}.ttf has no glyph for ${missing.map(([cp, n]) => `${n} (U+${cp.toString(16)})`).join(', ')}`)
        writeIfChanged(path.join(OUT, file), woff2(ttf))
        // U+0020 in the range makes the subset the first available font of the family in Chrome, so Chrome never loads
        // the full face for line metrics. Safari and Firefox also want a space glyph there, which neither font has, so
        // they load the full face as well and only get the text font saving. Icons look the same either way.
        css += `@font-face {\n  font-family: 'Font Awesome 6 Pro';\n  font-style: normal;\n  font-weight: ${weight};\n  font-display: block;\n` +
          `  src: url("./assets/fonts/fa-subset/${file}") format("woff2");\n  unicode-range: ${ranges([0x20, ...cps])};\n}\n`
      }
      writeIfChanged(path.join(OUT, '_faces.scss'), css)
    },
  }
}

// fa- tokens in every source file (DAO and exchange), as the class lists in templates and scripts spell them
function scanSources() {
  const classes = new Set(), dynamic = []
  const read = (file) => {
    const text = fs.readFileSync(file, 'utf8')
    for (const [name] of text.matchAll(/(?<![\w-])fa-[a-z0-9]+(?:-[a-z0-9]+)*/g)) classes.add(name)
    for (const m of text.matchAll(DYNAMIC)) dynamic.push(`${path.relative(APP, file)}:${text.slice(0, m.index).split('\n').length}  ${m[0]}`)
  }
  const walk = (dir) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, e.name)
      if (e.isDirectory()) { if (p !== OUT) walk(p) } else if (/\.(vue|ts|js|mjs|scss|css|html)$/.test(e.name)) read(p)
    }
  }
  walk(SRC)
  read(path.join(APP, 'index.html'))
  return { classes, dynamic }
}

// icon class -> codepoints, from the package CSS the DAO loads: .fa-x rules and the v4 .fa.fa-x shims
// (shims drawn from the brands font are left out, they never use the Pro faces)
function iconCodepoints() {
  const map = new Map()
  for (const [file, selector] of [['fontawesome.css', /^\.(fa-[a-z0-9-]+)$/], ['v4-shims.css', /^\.fa\.(fa-[a-z0-9-]+)$/]]) {
    const css = fs.readFileSync(path.join(FA, 'css', file), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '')
    const found = new Map(), brands = new Set()
    for (const [, selectors, body] of css.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
      const names = selectors.split(',').map((s) => selector.exec(s.trim())?.[1]).filter(Boolean)
      if (/Font Awesome 6 Brands/.test(body)) names.forEach((n) => brands.add(n))
      const value = /--fa\s*:\s*"((?:\\[0-9a-fA-F]+\s?|[^"])*)"/.exec(body)?.[1]
      if (value === undefined) continue
      const hex = [...value.matchAll(/\\([0-9a-fA-F]+)/g)].map((m) => parseInt(m[1], 16))
      const cps = hex.length ? hex : [...value].map((c) => c.codePointAt(0))
      for (const n of names) found.set(n, [...(found.get(n) || []), ...cps])
    }
    for (const [n, cps] of found) if (!brands.has(n)) map.set(n, [...(map.get(n) || []), ...cps])
  }
  return map
}

// Keeps the glyphs of the wanted codepoints plus every glyph mapped from ASCII, and every codepoint that maps
// to a kept glyph (aliases). Outlines and metrics are copied from the TTF as they are. head (bbox included),
// name and post come from the package WOFF2, the font browsers load today: the TTF has other timestamps, name
// bytes and underline metrics. hhea and OS/2 are the same in both. post drops the glyph names. Font Awesome
// fonts have no other tables, anything else stops the build.
function subset(src, pkg, wanted) {
  const t = tables(src)
  const unknown = Object.keys(t).filter((tag) => !['OS/2', 'cmap', 'glyf', 'head', 'hhea', 'hmtx', 'loca', 'maxp', 'name', 'post'].includes(tag))
  if (unknown.length) throw new Error(`Font Awesome subset: unexpected tables ${unknown.join(', ')}`)
  const w = woff2Tables(pkg)
  for (const tag of Object.keys(t)) {
    if (['head', 'name', 'post'].includes(tag)) continue
    if (w[tag] && !w[tag].equals(t[tag])) throw new Error(`Font Awesome subset: ${tag} differs between the package TTF and WOFF2`)
  }
  if (!w.head || !w.name || !w.post || w.head.readInt16BE(50) !== t.head.readInt16BE(50)) throw new Error('Font Awesome subset: the package WOFF2 head, name or post table is missing or does not match the TTF')
  const cmap = readCmap(t.cmap)
  const keep = new Set([0])
  for (const [cp, g] of cmap) if (cp < 0x80 || wanted.has(cp)) keep.add(g)
  const gids = [...keep].sort((a, b) => a - b)
  const newId = new Map(gids.map((g, i) => [g, i]))
  const cps = [...cmap.keys()].filter((cp) => keep.has(cmap.get(cp))).sort((a, b) => a - b)
  const long = t.head.readInt16BE(50) === 1
  const at = (g) => (long ? t.loca.readUInt32BE(4 * g) : 2 * t.loca.readUInt16BE(2 * g))
  const loca = Buffer.alloc((long ? 4 : 2) * (gids.length + 1))
  const glyphs = []
  let pos = 0
  gids.forEach((g, i) => {
    if (long) loca.writeUInt32BE(pos, 4 * i); else loca.writeUInt16BE(pos / 2, 2 * i)
    const glyph = pad4(t.glyf.subarray(at(g), at(g + 1)))
    // a composite glyph points at other glyph ids, which the renumbering would break
    if (glyph.length && glyph.readInt16BE(0) < 0) throw new Error(`Font Awesome subset: glyph ${g} is a composite glyph, which the subset cannot copy`)
    glyphs.push(glyph)
    pos += glyph.length
  })
  if (long) loca.writeUInt32BE(pos, 4 * gids.length); else loca.writeUInt16BE(pos / 2, 2 * gids.length)
  const metrics = t.hhea.readUInt16BE(34)
  const hmtx = Buffer.alloc(4 * gids.length)
  gids.forEach((g, i) => {
    hmtx.writeUInt16BE(t.hmtx.readUInt16BE(4 * Math.min(g, metrics - 1)), 4 * i)
    hmtx.writeInt16BE(g < metrics ? t.hmtx.readInt16BE(4 * g + 2) : t.hmtx.readInt16BE(4 * metrics + 2 * (g - metrics)), 4 * i + 2)
  })
  const hhea = Buffer.from(t.hhea)
  hhea.writeUInt16BE(gids.length, 34)
  const maxp = Buffer.from(t.maxp)
  maxp.writeUInt16BE(gids.length, 4)
  const post = Buffer.from(w.post.subarray(0, 32))
  post.writeUInt32BE(0x00030000, 0)
  const pairs = cps.map((cp) => [cp, newId.get(cmap.get(cp))])
  return { cps, ttf: sfnt({ 'OS/2': t['OS/2'], cmap: writeCmap(pairs), glyf: Buffer.concat(glyphs), head: Buffer.from(w.head), hhea, hmtx, loca, maxp, name: w.name, post }) }
}

// the tables a WOFF2 file stores untransformed, as bytes (transformed glyf, loca or hmtx are left out)
function woff2Tables(font) {
  let p = 48
  const uint = () => {
    let n = 0, b
    do { b = font[p++]; n = n * 128 + (b & 0x7f) } while (b & 0x80)
    return n
  }
  const dir = []
  for (let i = 0; i < font.readUInt16BE(12); i++) {
    const flags = font[p++]
    let tag = KNOWN_TAGS[flags & 0x3f]
    if ((flags & 0x3f) === 0x3f) { tag = font.toString('latin1', p, p + 4); p += 4 }
    const transformed = tag === 'glyf' || tag === 'loca' ? flags >> 6 !== 3 : flags >> 6 !== 0
    const length = uint()
    dir.push({ tag, transformed, length: transformed ? uint() : length })
  }
  const data = zlib.brotliDecompressSync(font.subarray(p, p + font.readUInt32BE(20)))
  const t = {}
  let offset = 0
  for (const { tag, transformed, length } of dir) {
    if (!transformed) t[tag] = data.subarray(offset, offset + length)
    offset += length
  }
  if (offset !== data.length) throw new Error('woff2: the table directory does not match the font data')
  return t
}

function tables(font) {
  const t = {}
  for (let i = 0; i < font.readUInt16BE(4); i++) {
    const r = 12 + 16 * i, offset = font.readUInt32BE(r + 8)
    t[font.toString('latin1', r, r + 4)] = font.subarray(offset, offset + font.readUInt32BE(r + 12))
  }
  return t
}

// codepoint -> glyph id from the Windows full Unicode (3,10) format 12 subtable
function readCmap(cmap) {
  for (let i = 0; i < cmap.readUInt16BE(2); i++) {
    const offset = cmap.readUInt32BE(8 + 8 * i)
    if (cmap.readUInt16BE(4 + 8 * i) !== 3 || cmap.readUInt16BE(6 + 8 * i) !== 10 || cmap.readUInt16BE(offset) !== 12) continue
    const map = new Map()
    for (let j = 0; j < cmap.readUInt32BE(offset + 12); j++) {
      const g = offset + 16 + 12 * j, start = cmap.readUInt32BE(g)
      for (let cp = start; cp <= cmap.readUInt32BE(g + 4); cp++) map.set(cp, cmap.readUInt32BE(g + 8) + cp - start)
    }
    return map
  }
  throw new Error('Font Awesome subset: no (3,10) format 12 cmap')
}

// the same four subtables as the package fonts: format 4 for (0,3) and (3,1), format 12 for (0,4) and (3,10)
function writeCmap(pairs) {
  const runs = (list) => {
    const out = []
    for (const [cp, g] of list) {
      const r = out[out.length - 1]
      if (r && cp === r[1] + 1 && g === r[2] + cp - r[0]) r[1] = cp; else out.push([cp, cp, g])
    }
    return out
  }
  const segs = [...runs(pairs.filter(([cp]) => cp <= 0xffff)), [0xffff, 0xffff, 0]]
  const n = segs.length, e = Math.floor(Math.log2(n))
  const f4 = Buffer.alloc(16 + 8 * n)
  f4.writeUInt16BE(4, 0); f4.writeUInt16BE(f4.length, 2); f4.writeUInt16BE(2 * n, 6)
  f4.writeUInt16BE(2 << e, 8); f4.writeUInt16BE(e, 10); f4.writeUInt16BE(2 * n - (2 << e), 12)
  segs.forEach(([start, end, g], i) => {
    f4.writeUInt16BE(end, 14 + 2 * i)
    f4.writeUInt16BE(start, 16 + 2 * n + 2 * i)
    f4.writeUInt16BE((g - start + 0x10000) & 0xffff, 16 + 4 * n + 2 * i)
  })
  const groups = runs(pairs)
  const f12 = Buffer.alloc(16 + 12 * groups.length)
  f12.writeUInt16BE(12, 0); f12.writeUInt32BE(f12.length, 4); f12.writeUInt32BE(groups.length, 12)
  groups.forEach(([start, end, g], i) => { f12.writeUInt32BE(start, 16 + 12 * i); f12.writeUInt32BE(end, 20 + 12 * i); f12.writeUInt32BE(g, 24 + 12 * i) })
  const head = Buffer.alloc(4 + 8 * 4)
  head.writeUInt16BE(4, 2)
  ;[[0, 3, f4], [0, 4, f12], [3, 1, f4], [3, 10, f12]].forEach(([platform, encoding, sub], i) => {
    head.writeUInt16BE(platform, 4 + 8 * i); head.writeUInt16BE(encoding, 6 + 8 * i)
    head.writeUInt32BE(sub === f4 ? head.length : head.length + f4.length, 8 + 8 * i)
  })
  return Buffer.concat([head, f4, f12])
}

// TrueType file from its tables, with table checksums and head.checkSumAdjustment
function sfnt(t) {
  const tags = Object.keys(t).sort(), n = tags.length, e = Math.floor(Math.log2(n))
  const dir = Buffer.alloc(12 + 16 * n)
  dir.writeUInt32BE(0x00010000, 0); dir.writeUInt16BE(n, 4)
  dir.writeUInt16BE(16 << e, 6); dir.writeUInt16BE(e, 8); dir.writeUInt16BE(16 * n - (16 << e), 10)
  t.head.writeUInt32BE(0, 8)
  let offset = dir.length
  tags.forEach((tag, i) => {
    dir.write(tag, 12 + 16 * i, 'latin1')
    dir.writeUInt32BE(checksum(t[tag]), 16 + 16 * i)
    dir.writeUInt32BE(offset, 20 + 16 * i)
    dir.writeUInt32BE(t[tag].length, 24 + 16 * i)
    offset += pad4(t[tag]).length
  })
  const font = Buffer.concat([dir, ...tags.map((tag) => pad4(t[tag]))])
  font.writeUInt32BE((0xb1b0afba - checksum(font)) >>> 0, dir.readUInt32BE(20 + 16 * tags.indexOf('head')) + 8)
  return font
}

// WOFF2 with every table stored untransformed (glyf/loca transform version 3), so decoding gives back the
// exact table bytes
const KNOWN_TAGS = ['cmap', 'head', 'hhea', 'hmtx', 'maxp', 'name', 'OS/2', 'post', 'cvt ', 'fpgm', 'glyf', 'loca', 'prep', 'CFF ',
  'VORG', 'EBDT', 'EBLC', 'gasp', 'hdmx', 'kern', 'LTSH', 'PCLT', 'VDMX', 'vhea', 'vmtx', 'BASE', 'GDEF', 'GPOS', 'GSUB', 'EBSC',
  'JSTF', 'MATH', 'CBDT', 'CBLC', 'COLR', 'CPAL', 'SVG ', 'sbix', 'acnt', 'avar', 'bdat', 'bloc', 'bsln', 'cvar', 'fdsc', 'feat',
  'fmtx', 'fvar', 'gvar', 'hsty', 'just', 'lcar', 'mort', 'morx', 'opbd', 'prop', 'trak', 'Zapf', 'Silf', 'Glat', 'Gloc', 'Feat', 'Sill']
export function woff2(ttf) {
  const t = tables(ttf), tags = Object.keys(t).sort()
  const dir = []
  let sfntSize = 12 + 16 * tags.length
  for (const tag of tags) {
    const known = KNOWN_TAGS.indexOf(tag)
    dir.push(Buffer.from([(known < 0 ? 63 : known) | (tag === 'glyf' || tag === 'loca' ? 0xc0 : 0)]))
    if (known < 0) dir.push(Buffer.from(tag, 'latin1'))
    dir.push(base128(t[tag].length))
    sfntSize += pad4(t[tag]).length
  }
  const data = Buffer.concat(tags.map((tag) => t[tag]))
  const z = zlib.brotliCompressSync(data, { params: {
    [zlib.constants.BROTLI_PARAM_MODE]: zlib.constants.BROTLI_MODE_FONT,
    [zlib.constants.BROTLI_PARAM_QUALITY]: 11,
    [zlib.constants.BROTLI_PARAM_SIZE_HINT]: data.length,
  } })
  if (!zlib.brotliDecompressSync(z).equals(data)) throw new Error('woff2: brotli round trip failed')
  const directory = Buffer.concat(dir)
  const length = (48 + directory.length + z.length + 3) & ~3
  const header = Buffer.alloc(48)
  header.write('wOF2', 0, 'latin1')
  header.writeUInt32BE(ttf.readUInt32BE(0), 4)
  header.writeUInt32BE(length, 8)
  header.writeUInt16BE(tags.length, 12)
  header.writeUInt32BE(sfntSize, 16)
  header.writeUInt32BE(z.length, 20)
  t.head.copy(header, 24, 4, 8) // WOFF version = head.fontRevision
  return Buffer.concat([header, directory, z], length)
}

function base128(n) {
  const bytes = [n & 0x7f]
  while ((n >>>= 7)) bytes.unshift(0x80 | (n & 0x7f))
  return Buffer.from(bytes)
}

function pad4(b) {
  return b.length % 4 ? Buffer.concat([b, Buffer.alloc(4 - (b.length % 4))]) : b
}

function checksum(b) {
  b = pad4(b)
  let sum = 0
  for (let i = 0; i < b.length; i += 4) sum = (sum + b.readUInt32BE(i)) >>> 0
  return sum
}

function ranges(cps) {
  const out = []
  for (const cp of [...new Set(cps)].sort((a, b) => a - b)) {
    const r = out[out.length - 1]
    if (r && cp === r[1] + 1) r[1] = cp; else out.push([cp, cp])
  }
  return out.map(([a, b]) => (a === b ? `U+${a.toString(16)}` : `U+${a.toString(16)}-${b.toString(16)}`)).join(', ')
}

function writeIfChanged(file, data) {
  if (!fs.existsSync(file) || !fs.readFileSync(file).equals(Buffer.from(data))) fs.writeFileSync(file, data)
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  for (const file of process.argv.slice(2)) {
    const out = file.replace(/\.ttf$/i, '.woff2')
    writeIfChanged(out, woff2(fs.readFileSync(file)))
    console.log(out, fs.statSync(out).size)
  }
}
